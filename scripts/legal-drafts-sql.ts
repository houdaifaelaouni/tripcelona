/**
 * Builds the SQL that loads the legal-page drafts (docs/legal/drafts/*.html)
 * into the `pages` table. The owner runs the output in the Supabase SQL editor.
 * The SQL first copies the current legal pages into a backup table, so
 * `legal_pages_backup_20261115` can restore them.
 *
 *   node --conditions=react-server --import tsx scripts/legal-drafts-sql.ts > legal-pages-draft.sql
 */
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { htmlToDoc } from "../src/lib/content/html-to-doc";

const PAGES: { slug: string; title: string }[] = [
  { slug: "politica-de-privacidad", title: "Política de privacidad" },
  { slug: "politica-de-cookies", title: "Política de cookies" },
  { slug: "condiciones-de-contratacion", title: "Condiciones generales de contratación" },
  { slug: "politica-de-devoluciones", title: "Política de cancelación y devoluciones" },
  { slug: "aviso-legal", title: "Aviso legal" },
];

const dir = join(import.meta.dirname, "..", "docs", "legal", "drafts");
const q = (s: string) => `'${s.replace(/'/g, "''")}'`;

const out: string[] = [
  "-- Legal pages: drafts pending legal review (generated by scripts/legal-drafts-sql.ts).",
  "-- Run once in the Supabase SQL editor. Restore with the block at the end.",
  "begin;",
  "",
  "create table if not exists public.legal_pages_backup_20261115 as",
  "  select * from public.pages where kind = 'legal';",
  "alter table public.legal_pages_backup_20261115 enable row level security;",
  "",
];

for (const p of PAGES) {
  const doc = htmlToDoc(readFileSync(join(dir, `${p.slug}.html`), "utf8"));
  out.push(
    "insert into public.pages (slug, title, content, status, kind, published_at)",
    `values (${q(p.slug)}, ${q(p.title)}, $doc$${JSON.stringify(doc)}$doc$::jsonb, 'published', 'legal', now())`,
    "on conflict (slug) do update set title = excluded.title, content = excluded.content,",
    "  status = 'published', kind = 'legal', updated_at = now();",
    "",
  );
}

out.push(
  "-- The old translations no longer match: other languages show the Spanish draft.",
  "delete from public.content_translations t using public.pages p",
  "  where t.entity = 'page' and t.entity_id = p.id and p.kind = 'legal';",
  "",
  "commit;",
  "",
  "-- RESTORE (only if you want the old texts back):",
  "-- update public.pages p set title = b.title, content = b.content, updated_at = now()",
  "--   from public.legal_pages_backup_20261115 b where b.id = p.id;",
  "",
);

process.stdout.write(out.join("\n"));
